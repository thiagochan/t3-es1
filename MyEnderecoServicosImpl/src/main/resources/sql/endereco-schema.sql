-- Tabelas de endereço, conforme o MER (3FN).
-- Executado por ConexaoBD a cada subida da aplicação, porque o H2 roda em memória.

CREATE TABLE UnidadeFederativa (
    siglaUF VARCHAR(2)  NOT NULL PRIMARY KEY,
    nomeUF  VARCHAR(50) NOT NULL
);

CREATE TABLE Cidade (
    idCidade INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome     VARCHAR(100) NOT NULL,
    siglaUF  VARCHAR(2)   NOT NULL,
    CONSTRAINT fk_cidade_uf FOREIGN KEY (siglaUF) REFERENCES UnidadeFederativa (siglaUF),
    CONSTRAINT uq_cidade UNIQUE (nome, siglaUF)
);

CREATE TABLE Bairro (
    idBairro INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome     VARCHAR(100) NOT NULL,
    CONSTRAINT uq_bairro UNIQUE (nome)
);

CREATE TABLE TipoLogradouro (
    siglaLogradouro VARCHAR(10) NOT NULL PRIMARY KEY,
    nomeLogradouro  VARCHAR(50) NOT NULL,
    CONSTRAINT uq_tipo_logradouro UNIQUE (nomeLogradouro)
);

CREATE TABLE Logradouro (
    idLogradouro    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(150) NOT NULL,
    siglaLogradouro VARCHAR(10)  NOT NULL,
    CONSTRAINT fk_logradouro_tipo FOREIGN KEY (siglaLogradouro) REFERENCES TipoLogradouro (siglaLogradouro),
    CONSTRAINT uq_logradouro UNIQUE (nome, siglaLogradouro)
);

-- Um mesmo CEP pode ter vários endereços (cidades pequenas têm um CEP para a cidade toda),
-- por isso a unicidade é da combinação completa, não só do CEP.
CREATE TABLE Endereco (
    idEndereco   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cep          VARCHAR(8) NOT NULL,
    idCidade     INTEGER    NOT NULL,
    idBairro     INTEGER    NOT NULL,
    idLogradouro INTEGER    NOT NULL,
    CONSTRAINT fk_endereco_cidade FOREIGN KEY (idCidade) REFERENCES Cidade (idCidade),
    CONSTRAINT fk_endereco_bairro FOREIGN KEY (idBairro) REFERENCES Bairro (idBairro),
    CONSTRAINT fk_endereco_logradouro FOREIGN KEY (idLogradouro) REFERENCES Logradouro (idLogradouro),
    CONSTRAINT uq_endereco UNIQUE (cep, idCidade, idBairro, idLogradouro)
);
